/**
 * 把编辑器文案翻成目标语言。未命中 → 原样返回（宁可中文，不显示裸 key）。
 * `lang` 接受 `zh-CN` / `zh` / `en-US` / `en`。
 */
export function localizeEditorText(text: string | undefined, lang: string | undefined): string {
  const value = (text ?? '').trim();
  if (!value) return '';
  if (!String(lang ?? '').toLowerCase().startsWith('zh')) {
    return EN[value] ?? value;
  }
  return value;
}

